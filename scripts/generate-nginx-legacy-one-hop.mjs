/**
 * Generates:
 * 1) deploy/nginx-legacy-one-hop.conf — nginx one-hop www/http → final URL
 * 2) src/lib/legacy-destinations.generated.ts — same map for Edge middleware
 *
 * Usage: node scripts/generate-nginx-legacy-one-hop.mjs
 */
import { createRequire } from "node:module";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { buildLegacyRedirects } = require("../legacy-redirects.cjs");

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const NGINX_OUT = join(ROOT, "deploy", "nginx-legacy-one-hop.conf");
const TS_OUT = join(ROOT, "src", "lib", "legacy-destinations.generated.ts");
const CANONICAL = "https://zond.agency";

const redirects = buildLegacyRedirects();
const exact = redirects.filter((r) => !r.source.includes(":"));
const patterns = redirects.filter((r) => r.source.includes(":"));

function nginxEscape(path) {
  return path.replace(/([.+/?*()[\]{}|$\\])/g, "\\$1");
}

function patternToNginxRegex(source) {
  return `^${source.replace(/:([A-Za-z_]+)/g, "([^/]+)")}$`;
}

function patternToNginxDest(destination) {
  let i = 0;
  return destination.replace(/:([A-Za-z_]+)/g, () => `$${++i}`);
}

function patternToJsRegex(source) {
  return `^${source.replace(/:([A-Za-z_]+)/g, "([^/]+)")}$`;
}

function patternToJsDest(destination) {
  let i = 0;
  return destination.replace(/:([A-Za-z_]+)/g, () => `\${${++i}}`);
}

// --- nginx ---
const nginx = [];
nginx.push("# AUTO-GENERATED by scripts/generate-nginx-legacy-one-hop.mjs — do not edit by hand.");
nginx.push(`# ${exact.length} exact + ${patterns.length} pattern redirects.`);
nginx.push("# Include inside www (:443) and http (:80) server blocks BEFORE any");
nginx.push("# blanket `return 301 https://zond.agency$request_uri;`.");
nginx.push("#");
nginx.push("#   include /var/www/zond-agency-site/deploy/nginx-legacy-one-hop.conf;");
nginx.push("");

for (const { source, destination } of exact) {
  nginx.push(
    `if ($request_uri ~ "^${nginxEscape(source)}(\\?.*)?$") { return 301 ${CANONICAL}${destination}$is_args$args; }`,
  );
}

nginx.push("");
for (const { source, destination } of patterns) {
  nginx.push(
    `if ($uri ~ "${patternToNginxRegex(source)}") { return 301 ${CANONICAL}${patternToNginxDest(destination)}$is_args$args; }`,
  );
}
nginx.push("");

mkdirSync(dirname(NGINX_OUT), { recursive: true });
writeFileSync(NGINX_OUT, `${nginx.join("\n")}\n`, "utf8");

// --- TypeScript for Edge middleware ---
const exactEntries = exact
  .map((r) => `  ${JSON.stringify(r.source)}: ${JSON.stringify(r.destination)},`)
  .join("\n");

const patternEntries = patterns
  .map((r) => {
    const keys = [...r.source.matchAll(/:([A-Za-z_]+)/g)].map((m) => m[1]);
    return `  { re: new RegExp(${JSON.stringify(patternToJsRegex(r.source))}), dest: ${JSON.stringify(r.destination)}, keys: ${JSON.stringify(keys)} },`;
  })
  .join("\n");

const ts = `/* AUTO-GENERATED by scripts/generate-nginx-legacy-one-hop.mjs — do not edit by hand. */

export const LEGACY_EXACT: Record<string, string> = {
${exactEntries}
};

type LegacyPattern = { re: RegExp; dest: string; keys: string[] };

export const LEGACY_PATTERNS: LegacyPattern[] = [
${patternEntries}
];

function toServiceUrlSlug(slug: string): string {
  return slug === "marketing-360" ? "marketing360" : slug;
}

/** Resolve old public pathname → final public path, or null. */
export function resolveLegacyDestination(pathname: string): string | null {
  const path = pathname.split("?")[0] || "/";
  const exactHit = LEGACY_EXACT[path];
  if (exactHit) return exactHit;

  for (const { re, dest, keys } of LEGACY_PATTERNS) {
    const match = path.match(re);
    if (!match) continue;
    let out = dest;
    keys.forEach((key, index) => {
      let value = match[index + 1] ?? "";
      if (key === "slug" && out.includes("/our-services/")) {
        value = toServiceUrlSlug(value);
      }
      out = out.replace(\`:\${key}\`, value);
    });
    return out;
  }
  return null;
}
`;

mkdirSync(dirname(TS_OUT), { recursive: true });
writeFileSync(TS_OUT, ts, "utf8");

console.log(`Wrote ${NGINX_OUT}`);
console.log(`Wrote ${TS_OUT}`);
console.log(`(${exact.length} exact, ${patterns.length} patterns)`);
