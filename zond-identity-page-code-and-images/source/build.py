def one(selector):
    matches = doc.cssselect(selector)
    assert len(matches) == 1, (selector, len(matches))
    return matches[0]

def set_text(selector, text):
    node = one(selector)
    node.text = text

def paragraph_list(selector, content):
    nodes = doc.cssselect(selector)
    assert len(nodes) == len(content), (selector, len(nodes), len(content))
    for node, value in zip(nodes, content):
        node.text = value

def cards(selector, records):
    nodes = doc.cssselect(selector)
    assert len(nodes) == len(records), (selector, len(nodes), len(records))
    for node, (title, description, image) in zip(nodes, records):
        node.cssselect('h3')[0].text = title
        node.cssselect('p')[0].text = description
        img = node.cssselect('img')[0]
        img.set('src', f'assets/{image}')
        img.set('alt', f'Ілюстрація напряму айдентики: {title}')

